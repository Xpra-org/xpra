import unittest
from binascii import unhexlify
from io import BytesIO
from struct import pack_into
from unittest.mock import patch

from xpra.codecs import codec_constants
from unit.test_util import silence_error


class DecoderSizeTest(unittest.TestCase):

    def test_image_size(self):
        with patch.object(codec_constants, "MAX_IMAGE_DIMENSION", 16384):
            codec_constants.check_image_size(1, 1)
            codec_constants.check_image_size(16384, 16384)
            for width, height in ((0, 1), (1, 0), (-1, 1), (1, -1), (16385, 1), (1, 16385)):
                with self.subTest(width=width, height=height):
                    with self.assertRaises(ValueError):
                        codec_constants.check_image_size(width, height)

    def test_jpeg(self):
        try:
            from PIL import Image
            from xpra.codecs.jpeg import decoder
        except ImportError as e:
            self.skipTest(str(e))
        buf = BytesIO()
        Image.new("RGB", (16, 16), (30, 60, 90)).save(buf, format="JPEG")
        data = buf.getvalue()
        oversized = bytearray(data)
        # Baseline JPEG SOF: precision, height, width, component count.
        sof = data.index(b"\xff\xc0")
        pack_into(">HH", oversized, sof + 5, 32768, 32768)
        with patch.object(codec_constants, "MAX_IMAGE_DIMENSION", 16384):
            for decode in (lambda value: decoder.decompress_to_rgb("RGBX", value), decoder.decompress_to_yuv):
                image = decode(data)
                self.assertEqual((image.get_width(), image.get_height()), (16, 16))
                image.free()
                with self.assertRaisesRegex(ValueError, "exceeds"):
                    decode(bytes(oversized))

    def test_vpx(self):
        try:
            from xpra.codecs.vpx import decoder
        except ImportError as e:
            self.skipTest(str(e))
        # Single 16x16 YUV420P keyframes generated by libvpx.
        frames = {
            "vp8": "1002009d012a100010001207088585889984880b82000c0d6000fefcad10",
            "vp9": "824983420000f000f60c38241c18900000204000229bffff277d585a0dad7e61b7a8f504913378277265f6086d9ef2e6d9eabf3c80",
        }
        for encoding, hexdata in frames.items():
            for width, height in ((16, 16), (32, 16), (16, 32)):
                with self.subTest(encoding=encoding, width=width, height=height):
                    dec = decoder.Decoder()
                    try:
                        dec.init_context(encoding, width, height, "YUV420P")
                        with silence_error(decoder):
                            image = dec.decompress_image(unhexlify(hexdata))
                        if (width, height) == (16, 16):
                            self.assertIsNotNone(image)
                            self.assertEqual((image.get_width(), image.get_height()), (16, 16))
                            image.free()
                        else:
                            self.assertIsNone(image)
                    finally:
                        dec.clean()
            with patch.object(codec_constants, "MAX_IMAGE_DIMENSION", 16384):
                for width, height in ((0, 16), (16, 0), (16385, 16), (16, 16385)):
                    with self.assertRaises(ValueError):
                        decoder.Decoder().init_context(encoding, width, height, "YUV420P")


if __name__ == '__main__':
    unittest.main()
