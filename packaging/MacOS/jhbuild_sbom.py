def warn(msg: str) -> None:
    sys.stderr.write(f"Warning: {msg}\n")


def jhbuild(*args: str) -> str:
    gtk_osx_build = os.path.expanduser("~/gtk-osx-build")
    cwd = gtk_osx_build if os.path.exists(gtk_osx_build) else os.getcwd()
    # we may be running from within a `jhbuild shell`, which sets `PYTHONNOUSERSITE`,
    # and that prevents the `jhbuild` wrapper from loading `pipenv` from the user site:
    env = dict(os.environ)
    env.pop("PYTHONNOUSERSITE", None)
    proc = subprocess.run(["jhbuild"] + list(args), cwd=cwd, env=env, capture_output=True, text=True)
    if proc.returncode != 0:
        raise RuntimeError(f"`jhbuild {' '.join(args)}` failed and returned {proc.returncode}")
    return proc.stdout


def get_installed_entries() -> dict[str, dict[str, str]]:
    # ie: <entry package="pango" version="1.58.2-d41d8cd98f00b204e9800998ecf8427e" installed="2026-10-15T12:33:40Z" />
    entries = {}
    for module in os.listdir(INFO_DIR):
        try:
            entry = ElementTree.parse(os.path.join(INFO_DIR, module)).getroot()
        except ElementTree.ParseError:
            continue
        entries[entry.get("package", module)] = dict(entry.attrib)
    return entries


def get_install_times() -> dict[str, str]:
    return {module: entry.get("installed", "") for module, entry in get_installed_entries().items()}


def load_manifests() -> tuple[dict[str, str], dict[str, str], dict[str, set[str]]]:
    """
    returns the module owning each installed path,
    the module owning each library and executable by filename,
    and the static archives of the modules which do not install any shared libraries
    """
    owners: dict[str, list[str]] = defaultdict(list)
    lib_owners: dict[str, list[str]] = defaultdict(list)
    archives: dict[str, set[str]] = {}
    for module in os.listdir(MANIFESTS_DIR):
        with open(os.path.join(MANIFESTS_DIR, module)) as f:
            paths = [line.strip() for line in f if line.strip()]
        for path in paths:
            if "/__pycache__/" in path:
                continue
            owners[path].append(module)
            if path.endswith((".dylib", ".so")) or path.startswith(("bin/", "libexec/")):
                lib_owners[os.path.basename(path)].append(module)
        if not any(path.endswith((".dylib", ".so")) for path in paths):
            if static := set(path for path in paths if path.endswith(".a")):
                archives[module] = static
    # some modules are built more than once with different options, ie: "freetype-no-harfbuzz" then "freetype",
    # the files in the prefix are the ones from the module that was installed last:
    times = get_install_times()

    def last_installed(modules: list[str]) -> str:
        return max(modules, key=lambda module: times.get(module, ""))

    return (
        {path: last_installed(modules) for path, modules in owners.items()},
        {name: last_installed(modules) for name, modules in lib_owners.items()},
        archives,
    )


def get_module_info(modules: Iterable[str]) -> dict[str, dict[str, str]]:
    try:
        output = jhbuild("info", *sorted(modules))
    except RuntimeError:
        # one of the modules is not found in the modulesets, so query them one at a time:
        output = ""
        for module in sorted(modules):
            try:
                output += jhbuild("info", module)
            except RuntimeError as e:
                warn(str(e))
    info: dict[str, dict[str, str]] = {}
    current: dict[str, str] = {}
    for line in output.splitlines():
        key, sep, value = line.partition(":")
        if not sep:
            continue
        key = key.strip()
        if key == "Name":
            current = info[value.strip()] = {}
        current[key] = value.strip()
    # modules which are no longer in the modulesets, ie: the bootstrap modules,
    # only have the version they were installed with, ie: "5.8.1-d41d8cd98f00b204e9800998ecf8427e":
    entries = get_installed_entries()
    for module in modules:
        if module not in info and module in entries:
            version = re.sub(r"-[0-9a-f]{32}$", "", entries[module].get("version", ""))
            info[module] = {"Name": module, "Version": version}
    return info


def get_symbols(path: str) -> set[str]:
    proc = subprocess.run(["nm", "-gUj", path], capture_output=True, text=True)
    return set(sym for sym in proc.stdout.split() if not sym.endswith(":"))


def is_macho(path: str) -> bool:
    with open(path, "rb") as f:
        magic = f.read(4)
    return magic in (b"\xcf\xfa\xed\xfe", b"\xce\xfa\xed\xfe", b"\xca\xfe\xba\xbe")


def file_rec(package: str, version: str, path: str) -> dict:
    rec = {
        "package": package,
        "version": version,
    }
    if os.path.isfile(path):
        rec["size"] = os.stat(path).st_size
        with open(path, "rb") as f:
            rec["checksum"] = hashlib.sha256(f.read()).hexdigest()
    return rec


def get_pc_version(pc_name: str) -> str:
    try:
        with open(os.path.join(X11_PREFIX, "lib", "pkgconfig", f"{pc_name}.pc")) as f:
            for line in f:
                if line.startswith("Version:"):
                    return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return ""


def get_xquartz_version() -> str:
    proc = subprocess.run(["pkgutil", "--pkg-info", XQUARTZ_PKGID], capture_output=True, text=True)
    for line in proc.stdout.splitlines():
        if line.startswith("version:"):
            return line.split(":", 1)[1].strip()
    return ""


def get_xterm_version(path: str) -> str:
    # ie: "XTerm(378)"
    proc = subprocess.run([path, "-version"], capture_output=True, text=True)
    m = re.search(r"\((\d+)\)", proc.stdout)
    return m.group(1) if m else ""


def get_x11_package(path: str) -> tuple[str, str]:
    # ie: "Frameworks/X11/lib/libX11.6.dylib" -> "libX11" from `x11.pc`
    name = os.path.basename(path).split(".", 1)[0]
    if path.startswith("Frameworks/X11/lib/"):
        pc_name = X11_PC.get(name, name.removeprefix("lib").lower())
        if version := get_pc_version(pc_name):
            return X11_PACKAGE.get(pc_name, name), version
    if name == "Xvfb" and (version := get_pc_version("xorg-server")):
        return "xorg-server", version
    # the copy in the bundle cannot run from there:
    if name == "xterm" and (version := get_xterm_version(os.path.join(X11_PREFIX, "bin", "xterm"))):
        return "xterm", version
    # the other X11 tools, ie: "xclock":
    return "xquartz", get_xquartz_version()


def walk(dirname: str) -> list[str]:
    paths = []
    for root, dirs, files in os.walk(dirname):
        dirs.sort()
        for filename in sorted(files):
            path = os.path.join(root, filename)
            if not os.path.islink(path):
                paths.append(os.path.relpath(path, dirname))
    return paths


def get_python_lib(contents: str) -> str:
    # ie: "lib/python3.14"
    pylibs = sorted(glob.glob(os.path.join(contents, "Resources", "lib", "python3.*")))
    if not pylibs:
        raise RuntimeError(f"python library directory not found in {contents!r}")
    return os.path.relpath(pylibs[-1], os.path.join(contents, "Resources"))


def get_extension_owners(owners: dict[str, str]) -> dict[str, str]:
    # ie: "lib/python3.14/site-packages/uvloop/loop.cpython-314-darwin.so" -> "lib/python3.14/site-packages/uvloop/loop"
    return {re.sub(r"\.[^/]*so$", "", path): module for path, module in owners.items() if path.endswith(".so")}


def get_python_owner(owners: dict[str, str], ext_owners: dict[str, str], python_lib: str, rel: str) -> str:
    # `rel` is relative to the python library directory, and py2app compiles the modules:
    rel = re.sub(r"__pycache__/([^/]+?)\.cpython-\d+(\.opt-\d)?\.pyc$", r"\1.py", rel)
    candidates = [rel]
    if rel.endswith(".pyc"):
        candidates.append(rel[:-1])
    for prefix in (f"{python_lib}/site-packages/", f"{python_lib}/", f"{python_lib}/lib-dynload/"):
        for candidate in candidates:
            if owner := owners.get(prefix + candidate):
                return owner
        # py2app moves the extension modules to `lib-dynload`, renames them to `.so`,
        # and replaces them with a `.pyc` loader:
        for suffix in (".pyc", ".so"):
            if rel.endswith(suffix) and (owner := ext_owners.get(prefix + rel[:-len(suffix)])):
                return owner
    return ""


def record_sbom(app_dir: str) -> tuple[dict[str, dict], dict[str, dict]]:
    contents = os.path.join(app_dir, "Contents")
    python_lib = get_python_lib(contents)
    pydir = f"Resources/{python_lib}/"
    owners, lib_owners, archives = load_manifests()
    ext_owners = get_extension_owners(owners)
    # path -> module (or X11 package and version):
    path_modules: dict[str, str] = {}
    x11: dict[str, tuple[str, str]] = {}
    unowned_binaries: list[str] = []
    unknown: list[str] = []

    def is_ours(path: str) -> bool:
        rel = path[len(pydir):] if path.startswith(pydir) else path
        return rel.startswith(OURS) or rel in GENERATED or any(rel.endswith(suffix) for suffix in SKIPPED_SUFFIXES)

    def python_owner(rel: str) -> str:
        return get_python_owner(owners, ext_owners, python_lib, rel)

    # binaries:
    for path in walk(contents):
        full_path = os.path.join(contents, path)
        if not is_macho(full_path):
            continue
        if path.startswith(pydir):
            # the python modules are resolved below,
            # but our own extensions may be statically linked with some libraries:
            if is_ours(path):
                unowned_binaries.append(path)
            continue
        if path.startswith("Frameworks/X11/"):
            x11[path] = get_x11_package(path)
            continue
        if path.startswith("Frameworks/lib-dynload/"):
            # py2app moves the python extensions here:
            module = python_owner(path[len("Frameworks/lib-dynload/"):])
        elif path.startswith("Resources/"):
            module = owners.get(path[len("Resources/"):], "")
        elif path == "Frameworks/bin/Python":
            # py2app's copy of the interpreter, ie: "bin/python3.14"
            module = owners.get("bin/" + os.path.basename(python_lib), "")
        else:
            module = ""
        module = module or lib_owners.get(os.path.basename(path), "")
        if module:
            path_modules[path] = module
        elif is_ours(path):
            unowned_binaries.append(path)
        else:
            unknown.append(path)
            unowned_binaries.append(path)

    # python modules, one entry per top level module unless it is shared by multiple jhbuild modules:
    def rec_python(rel: str, files: list[str], prefix: str) -> None:
        path = prefix + rel
        if is_ours(path):
            return
        modules = set()
        unknown_files = []
        for file in files:
            if is_ours(f"{path}/{file}" if file else path):
                continue
            if module := python_owner(f"{rel}/{file}" if file else rel):
                modules.add(module)
            elif not file.endswith((".pyi", ".typed")):
                unknown_files.append(f"{path}/{file}" if file else path)
        if len(modules) == 1:
            # the files we can't find are generated, ie: the `__pycache__` of the python3 `test` package
            path_modules[path] = modules.pop()
            return
        if not modules or files == [""]:
            unknown.extend(unknown_files)
            return
        children: dict[str, list[str]] = defaultdict(list)
        for file in files:
            if "/" in file:
                child, subpath = file.split("/", 1)
                children[child].append(subpath)
            elif file:
                rec_python(f"{rel}/{file}", [""], prefix)
        for child, subpaths in children.items():
            rec_python(f"{rel}/{child}", subpaths, prefix)

    pylib = os.path.join(contents, pydir)
    for child in sorted(os.listdir(pylib)):
        full_path = os.path.join(pylib, child)
        if child in ("site-packages.zip", "lib-dynload") or os.path.islink(full_path):
            continue
        if os.path.isdir(full_path):
            rec_python(child, walk(full_path), pydir)
        else:
            rec_python(child, [""], pydir)
    # py2app's `site-packages.zip`:
    zip_path = os.path.join(pylib, "site-packages.zip")
    if os.path.exists(zip_path):
        import zipfile
        top: dict[str, list[str]] = defaultdict(list)
        with zipfile.ZipFile(zip_path) as zf:
            for name in zf.namelist():
                if not name.endswith("/"):
                    child, _, subpath = name.partition("/")
                    top[child].append(subpath)
        for child, subpaths in sorted(top.items()):
            rec_python(child, subpaths, f"{pydir}site-packages.zip/")

    # static libraries are linked into other binaries:
    static_modules: set[str] = set()
    if archives:
        binaries = sorted(set(unowned_binaries) | set(path for path in path_modules if is_macho_path(contents, path)))
        with ThreadPoolExecutor() as executor:
            symbols_list = executor.map(get_symbols, (os.path.join(contents, path) for path in binaries))
        binary_symbols = dict(zip(binaries, symbols_list))
        for module, module_archives in sorted(archives.items()):
            symbols: set[str] = set()
            for archive in module_archives:
                symbols |= get_symbols(os.path.join(JHBUILD_PREFIX, archive))
            for path, path_symbols in binary_symbols.items():
                # ignore archives which only share a few generic symbols, ie: bison's `liby.a` and `_main`:
                if len((symbols & path_symbols) - {"_main"}) >= MIN_STATIC_SYMBOLS:
                    static_modules.add(module)
                    if path not in path_modules:
                        path_modules[path] = module

    if unknown:
        warn(f"no package data found for {len(unknown)} paths:")
        for path in unknown:
            warn(f" {path!r}")

    # now we know which modules we ship:
    modules = set(path_modules.values()) | static_modules
    module_info = get_module_info(modules)
    sbom: dict[str, dict] = {}
    for path, module in sorted(path_modules.items()):
        version = module_info.get(module, {}).get("Version", "")
        sbom[path] = file_rec(module, version, os.path.join(contents, path))
    for path, (package, version) in sorted(x11.items()):
        sbom[path] = file_rec(package, version, os.path.join(contents, path))

    packages: dict[str, dict] = {}
    for module in sorted(modules):
        info = module_info.get(module, {})

        def shipped(key: str) -> list[str]:
            # only keep the dependencies we ship, not the build tools or meta modules:
            return [dep.strip() for dep in info.get(key, "").split(",") if dep.strip() in modules]

        packages[module] = {
            "Name": module,
            "Version": info.get("Version", ""),
            "URL": info.get("URL", ""),
            "Depends On": shipped("Requires"),
            "Required By": shipped("Required by"),
        }
    for package, version in sorted(set(x11.values())):
        packages[package] = {
            "Name": package,
            "Version": version,
            "URL": X11_URL.get(package, "https://www.x.org/"),
        }
    return sbom, packages


def is_macho_path(contents: str, path: str) -> bool:
    full_path = os.path.join(contents, path)
    return os.path.isfile(full_path) and is_macho(full_path)


def save_build_info(app_dir: str, sbom: dict, packages: dict) -> None:
    contents = os.path.join(app_dir, "Contents")
    build_info = os.path.join(contents, "Resources", get_python_lib(contents), "xpra", "build_info.py")
    with open(build_info) as f:
        lines = f.readlines()
    # replace any previous values:
    lines = [line for line in lines if not re.match(r"(sbom|packages)\s*=", line)]
    lines.append(f"\n# {len(sbom)} SBOM path entries:\n")
    lines.append(f"sbom={sbom!r}\n")
    lines.append(f"\n# {len(packages)} packages:\n")
    lines.append(f"packages={packages!r}\n")
    with open(build_info, "w") as f:
        f.writelines(lines)


def load_identifiers() -> Callable[[str, str], tuple[str, list[str], list[str]]]:
    def identify(package_name: str, version: str) -> tuple[str, list[str], list[str]]:
        cpe_version = re.sub(r"([:*?\\])", r"\\\1", version)
        cpes = [f"cpe:2.3:a:{vendor_product}:{cpe_version}:*:*:*:*:*:*:*" for vendor_product in CPES.get(package_name, ())]
        purls = [f"{PURLS[package_name]}@{version}"] if package_name in PURLS else []
        return version, cpes, purls
    return identify


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        sys.stderr.write(f"usage: {argv[0]} APP_DIR\n")
        return 1
    app_dir = argv[1]
    sbom, packages = record_sbom(app_dir)
    save_build_info(app_dir, sbom, packages)
    print(f"recorded {len(sbom)} SBOM path entries and {len(packages)} packages")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
